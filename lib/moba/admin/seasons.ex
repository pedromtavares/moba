defmodule Moba.Admin.Seasons do
  @moduledoc """
  Admin functions for managing Seasons, mostly generated by Torch package.
  """

  alias Moba.{Repo, Game}
  alias Game.Schema.{Player, Hero, Match, Season, TrainingTeam}
  alias Game.Query.{PlayerQuery, HeroQuery, SkillQuery}

  import Ecto.Query
  import Torch.Helpers, only: [sort: 1, paginate: 4]
  import Filtrex.Type.Config

  @pagination [page_size: 50]
  @pagination_distance 5

  def paginate(params \\ %{}) do
    params =
      params
      |> Map.put_new("sort_direction", "desc")
      |> Map.put_new("sort_field", "inserted_at")

    {:ok, sort_direction} = Map.fetch(params, "sort_direction")
    {:ok, sort_field} = Map.fetch(params, "sort_field")

    with {:ok, filter} <- Filtrex.parse_params(filter_config(:seasons), params["season"] || %{}),
         %Scrivener.Page{} = page <- do_paginate(filter, params) do
      {:ok,
       %{
         seasons: page.entries,
         page_number: page.page_number,
         page_size: page.page_size,
         total_pages: page.total_pages,
         total_entries: page.total_entries,
         distance: @pagination_distance,
         sort_field: sort_field,
         sort_direction: sort_direction
       }}
    else
      {:error, error} -> {:error, error}
      error -> {:error, error}
    end
  end

  def list do
    Repo.all(Season)
  end

  def list_recent do
    Repo.all(from m in Season, limit: 10, order_by: [desc: m.id])
  end

  def get!(id), do: Repo.get!(Season, id)

  def update(%Season{} = season, attrs) do
    season
    |> Season.changeset(attrs)
    |> Repo.update()
  end

  def change(%Season{} = season) do
    Season.changeset(season, %{})
  end

  def current_active_players do
    players =
      PlayerQuery.non_bots()
      |> PlayerQuery.non_guests()
      |> PlayerQuery.currently_active(168)
      |> Repo.all()
      |> Repo.preload(:user)

    player_ids = Enum.map(players, & &1.id)
    activities = Game.CommunityActivity.latest_for_players(player_ids)
    heroes = latest_player_heroes(player_ids)

    best_heroes =
      from(h in HeroQuery.top_ranked_for_players(player_ids),
        where: h.pve_ranking >= 1
      )
      |> Repo.all()
      |> Map.new(&{&1.player_id, &1})

    players
    |> Enum.map(fn player ->
      player
      |> Map.put(:latest_hero, Map.get(heroes, player.id))
      |> Map.put(:recent_activity, Map.get(activities, player.id))
      |> Map.put(:best_ranked_hero, Map.get(best_heroes, player.id))
    end)
  end

  defp latest_player_heroes(player_ids) do
    from(h in Hero,
      where: h.player_id in ^player_ids and is_nil(h.archived_at),
      distinct: h.player_id,
      order_by: [desc: h.inserted_at, desc: h.id],
      preload: [:avatar]
    )
    |> Repo.all()
    |> Map.new(&{&1.player_id, &1})
  end

  def current_guests do
    PlayerQuery.non_bots()
    |> PlayerQuery.guests()
    |> PlayerQuery.recently_created()
    |> guest_cards()
    |> Enum.reject(&(&1.heroes == []))
  end

  def current_guest(player_id) do
    from(p in Player, where: p.id == ^player_id and is_nil(p.user_id))
    |> guest_cards()
    |> List.first()
  end

  defp guest_cards(query) do
    players = query |> Repo.all() |> Repo.preload(current_pve_hero: [:avatar, skills: SkillQuery.ordered()])
    teams = recent_guest_teams(Enum.map(players, & &1.id))

    Enum.map(players, fn player ->
      team = teams[player.id]

      {heroes, league_tier} =
        case guest_roster(team) do
          {[], _} when not is_nil(player.current_pve_hero) ->
            hero = player.current_pve_hero
            {[guest_hero(hero)], hero.league_tier}

          roster ->
            roster
        end

      last_online_at =
        if team, do: Enum.max([player.updated_at, team.updated_at], NaiveDateTime), else: player.updated_at

      %{
        player: Map.take(player, [:id, :pve_tier, :inserted_at]),
        heroes: heroes,
        league_tier: league_tier,
        last_online_at: last_online_at
      }
    end)
  end

  defp recent_guest_teams([]), do: %{}

  defp recent_guest_teams(player_ids) do
    from(team in TrainingTeam,
      where: team.player_id in ^player_ids and is_nil(team.archived_at) and is_nil(team.user_id),
      where: team.phase in ["playing", "engagement", "finished", "draft"],
      distinct: team.player_id,
      order_by: [asc: fragment("? = 'draft'", team.phase), desc: team.id]
    )
    |> Repo.all()
    |> Map.new(&{&1.player_id, &1})
  end

  defp guest_roster(nil), do: {[], nil}

  defp guest_roster(team) do
    case Game.TeamRuns.read_state(team) do
      {:ok, %{phase: :draft, picks: picks}} ->
        heroes =
          for %{avatar: avatar, skills: skills} <- picks do
            %{avatar: avatar, skills: skills ++ List.wrap(avatar.ultimate), level: 1, league_tier: 0, fallen: false}
          end

        {heroes, if(heroes != [], do: 0)}

      {:ok, run} ->
        heroes = for %{hero: hero} <- Game.TeamTraining.team(run), do: guest_hero(hero)
        {heroes, run.league_tier}

      {:error, :invalid_snapshot} ->
        {[], nil}
    end
  end

  defp guest_hero(hero) do
    %{
      avatar: hero.avatar,
      skills: hero.skills,
      level: hero.level,
      league_tier: hero.league_tier,
      fallen: hero.pve_state == "dead"
    }
  end

  def active_players_count do
    PlayerQuery.non_bots()
    |> PlayerQuery.non_guests()
    |> Repo.aggregate(:count)
  end

  def trained_heroes_count do
    HeroQuery.non_bots() |> HeroQuery.finished() |> Repo.aggregate(:count)
  end

  def players_count do
    latest = from(p in Player, order_by: [desc: p.id], limit: 1) |> Repo.all() |> List.first()
    (latest && Map.get(latest, :id)) || 0
  end

  def heroes_count do
    latest = from(h in Hero, order_by: [desc: h.id], limit: 1) |> Repo.all() |> List.first()
    (latest && Map.get(latest, :id)) || 0
  end

  def matches_count do
    latest = from(m in Match, order_by: [desc: m.id], limit: 1) |> Repo.all() |> List.first()
    (latest && Map.get(latest, :id)) || 0
  end

  def masters_count do
    HeroQuery.non_bots()
    |> HeroQuery.masters()
    |> Repo.aggregate(:count)
  end

  def grandmasters_count do
    HeroQuery.non_bots()
    |> HeroQuery.grandmasters()
    |> Repo.aggregate(:count)
  end

  def undefeated_count do
    HeroQuery.non_bots()
    |> HeroQuery.undefeated()
    |> Repo.aggregate(:count)
  end

  defp do_paginate(filter, params) do
    Season
    |> Filtrex.query(filter)
    |> order_by(^sort(params))
    |> paginate(Repo, params, @pagination)
  end

  defp filter_config(:seasons) do
    defconfig do
      text(:changelog)
      boolean(:active)
    end
  end
end
